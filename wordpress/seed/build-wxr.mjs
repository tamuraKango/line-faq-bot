// posts/*.html から、WordPress のインポート用ファイル（WXR）を作る
// WP-CLI が使えない WordPress.com で、管理画面の「インポート」から読み込むために使う
// 使い方: npm run seed:wxr  → wordpress/seed/faq-import.xml ができる
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const postsDir = join(here, 'posts');
const outFile = join(here, 'faq-import.xml');

// WordPress.com のインポーターは、本物の書き出しファイルと同じ項目（generator やサイトの URL など）がないと受け付けない
const SITE_URL = 'http://localhost:8080';

// CDATA の中に「]]>」があると閉じてしまうので、分割して入れる
const cdata = (text) => `<![CDATA[${text.replaceAll(']]>', ']]]]><![CDATA[>')}]]>`;

const files = readdirSync(postsDir)
  .filter((name) => name.endsWith('.html'))
  .sort();

const items = files.map((name, index) => {
  // seed.sh と同じ形式：1行目がタイトル、2行目以降が本文。スラッグは先頭の番号を外したファイル名
  const [title, ...body] = readFileSync(join(postsDir, name), 'utf8').split('\n');
  const slug = basename(name, '.html').replace(/^[0-9]*-/, '');
  const id = index + 1;
  // 番号順に並ぶように、1分ずつずらした投稿日時にする
  const time = new Date(Date.UTC(2026, 0, 1, 0, index));
  const date = time.toISOString().slice(0, 19).replace('T', ' ');
  return `	<item>
		<title>${cdata(title.trim())}</title>
		<link>${SITE_URL}/${slug}/</link>
		<pubDate>${time.toUTCString().replace('GMT', '+0000')}</pubDate>
		<dc:creator>${cdata('admin')}</dc:creator>
		<guid isPermaLink="false">${SITE_URL}/?p=${id}</guid>
		<description></description>
		<content:encoded>${cdata(body.join('\n').trim())}</content:encoded>
		<excerpt:encoded>${cdata('')}</excerpt:encoded>
		<wp:post_id>${id}</wp:post_id>
		<wp:post_date>${cdata(date)}</wp:post_date>
		<wp:post_date_gmt>${cdata(date)}</wp:post_date_gmt>
		<wp:post_modified>${cdata(date)}</wp:post_modified>
		<wp:post_modified_gmt>${cdata(date)}</wp:post_modified_gmt>
		<wp:comment_status>${cdata('closed')}</wp:comment_status>
		<wp:ping_status>${cdata('closed')}</wp:ping_status>
		<wp:post_name>${cdata(slug)}</wp:post_name>
		<wp:status>${cdata('publish')}</wp:status>
		<wp:post_parent>0</wp:post_parent>
		<wp:menu_order>0</wp:menu_order>
		<wp:post_type>${cdata('post')}</wp:post_type>
		<wp:post_password>${cdata('')}</wp:post_password>
		<wp:is_sticky>0</wp:is_sticky>
		<category domain="category" nicename="uncategorized">${cdata('Uncategorized')}</category>
	</item>`;
});

const author = [
  '<wp:author_id>1</wp:author_id>',
  `<wp:author_login>${cdata('admin')}</wp:author_login>`,
  `<wp:author_email>${cdata('admin@example.com')}</wp:author_email>`,
  `<wp:author_display_name>${cdata('admin')}</wp:author_display_name>`,
  `<wp:author_first_name>${cdata('')}</wp:author_first_name>`,
  `<wp:author_last_name>${cdata('')}</wp:author_last_name>`,
].join('');

const xml = `<?xml version="1.0" encoding="UTF-8" ?>
<!-- This is a WordPress eXtended RSS file generated by WordPress as an export of your site. -->
<!-- It contains information about your site's posts, pages, comments, categories, and other content. -->
<!-- You may use this file to transfer that content from one site to another. -->
<!-- This file is not intended to serve as a complete backup of your site. -->
<!-- generator="WordPress/7.1.4" created="2026-01-01 00:00" -->
<rss version="2.0"
	xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
	xmlns:content="http://purl.org/rss/1.0/modules/content/"
	xmlns:wfw="http://wellformedweb.org/CommentAPI/"
	xmlns:dc="http://purl.org/dc/elements/1.1/"
	xmlns:wp="http://wordpress.org/export/1.2/"
>

<channel>
	<title>サンプル株式会社 社内FAQ</title>
	<link>${SITE_URL}</link>
	<description></description>
	<pubDate>Thu, 01 Jan 2026 00:00:00 +0000</pubDate>
	<language>ja</language>
	<wp:wxr_version>1.2</wp:wxr_version>
	<wp:base_site_url>${SITE_URL}</wp:base_site_url>
	<wp:base_blog_url>${SITE_URL}</wp:base_blog_url>

	<wp:author>${author}</wp:author>

	<generator>https://wordpress.org/?v=7.1.4</generator>

${items.join('\n')}
</channel>
</rss>
`;

writeFileSync(outFile, xml);
console.log(`${files.length} 件の記事を書き出しました: ${outFile}`);
